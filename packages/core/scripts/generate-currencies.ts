import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

// Builds src/currencies.generated.ts from the official ISO 4217 List One XML
// saved in data/. The table is never typed by hand (threat model C8).
// Entries whose minor unit is "N.A." (gold, silver, SDR, testing codes) have no
// smallest unit to count in, so they are left out on purpose.

const xmlPath = fileURLToPath(new URL("../data/iso4217-list-one.xml", import.meta.url));
const outPath = fileURLToPath(new URL("../src/currencies.generated.ts", import.meta.url));

const xml = readFileSync(xmlPath, "utf8");

const published = /<ISO_4217\s+Pblshd="(\d{4}-\d{2}-\d{2})"/.exec(xml)?.[1];
if (published === undefined) {
  throw new Error("generate-currencies: no Pblshd date on the ISO_4217 root element");
}

function field(entry: string, tag: string): string | undefined {
  return new RegExp(`<${tag}(?:\\s[^>]*)?>([^<]*)</${tag}>`).exec(entry)?.[1]?.trim();
}

const digitsByCode = new Map<string, number>();
for (const match of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
  const entry = match[1] ?? "";
  const code = field(entry, "Ccy");
  const minor = field(entry, "CcyMnrUnts");
  if (code === undefined || minor === undefined || !/^[0-9]+$/.test(minor)) continue;
  // Fail loudly on anything unexpected rather than ship a table with a gap or a guess.
  if (!/^[A-Z]{3}$/.test(code)) {
    throw new Error(`generate-currencies: malformed currency code "${code}"`);
  }
  const digits = Number(minor);
  const seen = digitsByCode.get(code);
  if (seen !== undefined && seen !== digits) {
    throw new Error(`generate-currencies: ${code} listed with ${seen} and ${digits} minor units`);
  }
  digitsByCode.set(code, digits);
}

if (digitsByCode.size === 0) {
  throw new Error("generate-currencies: no currencies found, the XML layout may have changed");
}

const codes = [...digitsByCode.keys()].sort();
const rows = codes.map((code) => `  Object.freeze({ code: "${code}", digits: ${digitsByCode.get(code)} }),`);

const source = `// Generated by scripts/generate-currencies.ts from data/iso4217-list-one.xml.
// Do not edit by hand: rerun the script after replacing the XML.

export const ISO4217_PUBLISHED = "${published}";

export const ISO4217_CURRENCIES: readonly { readonly code: string; readonly digits: number }[] = Object.freeze([
${rows.join("\n")}
]);
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, source, "utf8");
console.log(`Wrote ${codes.length} currencies (ISO 4217 list published ${published}) to src/currencies.generated.ts`);
